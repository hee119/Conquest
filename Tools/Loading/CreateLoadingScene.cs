var previous = UnityEngine.SceneManagement.SceneManager.GetActiveScene();
var source = UnityEngine.Object.FindFirstObjectByType<ExpBar>(UnityEngine.FindObjectsInactive.Include);
if (source == null) throw new System.Exception("Stage experience bar is required.");
var scene = UnityEditor.SceneManagement.EditorSceneManager.NewScene(UnityEditor.SceneManagement.NewSceneSetup.EmptyScene, UnityEditor.SceneManagement.NewSceneMode.Additive);
UnityEngine.SceneManagement.SceneManager.SetActiveScene(scene);
var camera = new UnityEngine.GameObject("Loading Camera").AddComponent<UnityEngine.Camera>();
camera.clearFlags = UnityEngine.CameraClearFlags.SolidColor;
camera.backgroundColor = UnityEngine.Color.black;
var canvas = new UnityEngine.GameObject("Loading Canvas", typeof(UnityEngine.RectTransform), typeof(UnityEngine.Canvas), typeof(UnityEngine.UI.CanvasScaler)).GetComponent<UnityEngine.Canvas>();
canvas.renderMode = UnityEngine.RenderMode.ScreenSpaceOverlay;
var scaler = canvas.GetComponent<UnityEngine.UI.CanvasScaler>();
scaler.uiScaleMode = UnityEngine.UI.CanvasScaler.ScaleMode.ScaleWithScreenSize;
scaler.referenceResolution = new UnityEngine.Vector2(1920,1080);
scaler.matchWidthOrHeight = 0.5f;
var bar = UnityEngine.Object.Instantiate(source, canvas.transform, false);
bar.name = "Loading Experience Bar";
var rect = bar.GetComponent<UnityEngine.RectTransform>();
rect.anchorMin = rect.anchorMax = new UnityEngine.Vector2(0.5f,0.5f);
rect.pivot = new UnityEngine.Vector2(0.5f,0.5f);
rect.anchoredPosition = new UnityEngine.Vector2(0,-40);
rect.sizeDelta = new UnityEngine.Vector2(1100,70);
rect.localScale = UnityEngine.Vector3.one;
foreach (var name in new[]{"Background", "Fill Area"})
{
    var child = bar.transform.Find(name) as UnityEngine.RectTransform;
    if(child == null) continue;
    child.anchorMin = UnityEngine.Vector2.zero;
    child.anchorMax = UnityEngine.Vector2.one;
    child.offsetMin = child.offsetMax = UnityEngine.Vector2.zero;
}
var barData = new UnityEditor.SerializedObject(bar);
barData.FindProperty("loadingMode").boolValue = true;
barData.ApplyModifiedPropertiesWithoutUndo();
var slider = bar.GetComponent<UnityEngine.UI.Slider>();
slider.interactable = false;
slider.onValueChanged.RemoveAllListeners();
slider.minValue = 0; slider.maxValue = 1; slider.value = 0;
var label = new UnityEngine.GameObject("Loading Progress",typeof(UnityEngine.RectTransform),typeof(TMPro.TextMeshProUGUI)).GetComponent<TMPro.TextMeshProUGUI>();
label.transform.SetParent(canvas.transform,false);
label.font = UnityEditor.AssetDatabase.LoadAssetAtPath<TMPro.TMP_FontAsset>("Assets/Pont/GowunBatang-Regular SDF.asset");
label.text = "Loading... 0%"; label.fontSize = 40; label.alignment = TMPro.TextAlignmentOptions.Center; label.color = UnityEngine.Color.white;
label.rectTransform.anchorMin = label.rectTransform.anchorMax = new UnityEngine.Vector2(0.5f,0.5f);
label.rectTransform.anchoredPosition = new UnityEngine.Vector2(0,80);
label.rectTransform.sizeDelta = new UnityEngine.Vector2(1000,90);
new UnityEngine.GameObject("PoolManager").AddComponent<PoolManager>();
var controller = new UnityEngine.GameObject("Startup Loading").AddComponent<StartupLoading>();
var data = new UnityEditor.SerializedObject(controller);
data.FindProperty("progressBar").objectReferenceValue = bar;
data.FindProperty("progressText").objectReferenceValue = label;
data.ApplyModifiedPropertiesWithoutUndo();
UnityEditor.SceneManagement.EditorSceneManager.SaveScene(scene,"Assets/Scenes/Loading.unity");
var scenes = new System.Collections.Generic.List<UnityEditor.EditorBuildSettingsScene>();
scenes.Add(new UnityEditor.EditorBuildSettingsScene("Assets/Scenes/Loading.unity",true));
foreach(var entry in UnityEditor.EditorBuildSettings.scenes) if(entry.path != "Assets/Scenes/Loading.unity") scenes.Add(entry);
UnityEditor.EditorBuildSettings.scenes = scenes.ToArray();
UnityEditor.AssetDatabase.SaveAssets();
UnityEngine.SceneManagement.SceneManager.SetActiveScene(previous);
UnityEditor.SceneManagement.EditorSceneManager.CloseScene(scene,true);
return "Loading scene saved; build startup set.";
